window.JanSetuI18n = {
  getLanguage: function () {
    return window.JanSetuStorage ? window.JanSetuStorage.getLanguage() : 'hi';
  },

  t: function (key) {
    const lang = this.getLanguage();
    const dict = window.JANSETU_TRANSLATIONS[lang] || window.JANSETU_TRANSLATIONS.hi;
    return dict[key] !== undefined ? dict[key] : (window.JANSETU_TRANSLATIONS.en[key] || key);
  },

  setLanguage: function (lang) {
    if (window.JanSetuStorage) {
      window.JanSetuStorage.setLanguage(lang);
    }
    this.applyTranslations();
    window.dispatchEvent(new CustomEvent('jansetu:lang-changed', { detail: { lang: lang } }));
  },

  toggleLanguage: function () {
    const current = this.getLanguage();
    const next = current === 'hi' ? 'en' : 'hi';
    this.setLanguage(next);
  },

  applyTranslations: function () {
    const lang = this.getLanguage();
    const dict = window.JANSETU_TRANSLATIONS[lang] || window.JANSETU_TRANSLATIONS.hi;

    // Apply to elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Apply to inputs with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Apply to elements with data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.setAttribute('title', dict[key]);
      }
    });

    // Update language toggle button label
    const toggleButtons = document.querySelectorAll('.lang-toggle-btn');
    toggleButtons.forEach(btn => {
      btn.textContent = lang === 'hi' ? 'English' : 'हिंदी';
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang;
  }
};

document.addEventListener('DOMContentLoaded', () => {
  JanSetuI18n.applyTranslations();
});
